// Writes js/trade_goods.js: the sea trade goods, by level, as the
// barter table hands them over or takes them in.
//
// The goods are not in any recipe, vendor list or quest, so without
// this the app's item list -- the Inventory, Find, Log a trip -- had
// no way to record a [Level 4] good a player was holding, though the
// chart's hold and carry lists already read them out of the stock.
// Run on its own, or by tools/build-barter.mjs after a fresh pull.

import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const SRC = new URL('../js/all_barter.json', import.meta.url);
const OUT = new URL('../js/trade_goods.js', import.meta.url);
const LEVEL = /^\[Level (\d)\]/;

export async function buildTradeGoods() {
	const data = JSON.parse(await readFile(SRC, 'utf8'));
	const byLevel = {};
	const add = name => {
		const m = LEVEL.exec(name || '');
		if (!m) return;
		(byLevel[m[1]] ||= new Set()).add(name);
	};
	for (const e of data) {
		add(e.name);
		for (const s of e.sources) add(s.give && s.give.name);
	}
	const levels = Object.keys(byLevel).map(Number).sort((a, b) => a - b);
	const body = levels.map(lv => `\t${lv}: [\n${[...byLevel[lv]].sort((a, b) => a.localeCompare(b)).map(n => `\t\t${JSON.stringify(n)}`).join(',\n')}\n\t]`).join(',\n');
	const total = levels.reduce((n, lv) => n + byLevel[lv].size, 0);
	const src = `// The sea trade goods, by level: every [Level N] good the barter
// table hands over or takes in. Generated by tools/build-trade-goods.mjs
// from js/all_barter.json -- do not edit by hand; rebuild after a pull.
//
// ${total} goods over ${levels.length} levels. What each level weighs and
// sells for is GOODS in barter.js; which islands deal each one is the
// table itself.

export const tradeGoods = {
${body}
};

/** Every good, lowest level first. */
export const tradeGoodNames = Object.values(tradeGoods).flat();
`;
	await writeFile(OUT, src);
	return { total, levels: levels.length };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
	const { total, levels } = await buildTradeGoods();
	console.log(`${total} trade goods over ${levels} levels`);
}
