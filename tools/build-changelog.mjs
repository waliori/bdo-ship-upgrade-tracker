// CHANGELOG.md, written from js/about.js.
//
// The release notes live in the app because the app shows them: the
// What's New dialog reads RELEASES directly. Keeping a second copy in
// Markdown by hand is how the two end up disagreeing, so the file is
// generated instead, and a test fails if it is out of date.
//
//   node tools/build-changelog.mjs          # write it
//   node tools/build-changelog.mjs --check  # fail if it would change
//
// The pictures are the narrow copies under docs/media/small, the same
// ones the dialog shows. The full-size originals are several times the
// weight, and a changelog is read past rather than studied: pointing at
// them kept a dozen megabytes of GIFs in the tree for this file alone.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { RELEASES, RELEASE, CHANGES, LATEST } from '../js/about.js';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(root, 'CHANGELOG.md');
// The three facts the page needs at boot -- which release this is and
// the newest diary line -- without the 170 KB of notes behind them,
// which are fetched only when What's new or Help is opened. Written
// here, beside the changelog, so it cannot drift from about.js either.
const TINY = path.join(root, 'js/release.js');

/** `<b>`, `<i>` and `<kbd>` are the only markup the notes use. */
const md = html => html
	.replace(/<\/?b>/g, '**')
	.replace(/<\/?i>/g, '*')
	.replace(/<kbd>(.*?)<\/kbd>/g, '`$1`');

const HEAD = `# Changelog

What arrived between one version of this app and the next, written for
someone who has been away. The same notes are in the app itself, under
**Menu → What's new** — this file is generated from them by
\`node tools/build-changelog.mjs\`, so the two cannot drift apart.
`;

// Every block stands alone, separated by a blank line: run an image
// straight into a paragraph and Markdown makes them one, and a list
// without a blank line above it is not a list at all.
const body = RELEASES.flatMap(r => {
	const blocks = [`## ${r.id} — ${r.name}`, `*${r.date}*`, md(r.blurb)];
	// Who asked for it goes first, as it does in the dialog.
	const t = r.thanks;
	if (t && t.who && t.who.length) {
		blocks.push('### Asked for by you', md(t.text));
		blocks.push(t.who.map(w => `- **${w.name}** — ${w.said ? `*“${md(w.said)}”* ` : ''}${md(w.did)}`).join('\n'));
		if (t.also && t.also.length) blocks.push(`Bugs reported and runs tested by ${t.also.map(n => `**${n}**`).join(', ')}.`);
		if (t.foot) blocks.push(md(t.foot));
	}
	for (const s of r.sections) {
		blocks.push(`### ${md(s.title)}`);
		if (s.media) blocks.push(`![${s.alt || ''}](${s.media})`);
		if (s.text) blocks.push(md(s.text));
		if (s.points) blocks.push(s.points.map(p => `- ${md(p)}`).join('\n'));
	}
	return blocks;
});

const text = `${HEAD}\n${body.join('\n\n')}\n`;

const tiny = `// Generated by tools/build-changelog.mjs from js/about.js -- do not edit.
//
// What the page needs to know at boot about the release notes: which
// release this build is, and the newest working entry. The notes
// themselves stay in about.js, imported when they are opened.

/** The release this build is; what the What's New dialog is keyed on. */
export const RELEASE = ${JSON.stringify(RELEASE)};

/** The newest diary entry, as the "seen" key and as its title. */
export const LATEST = ${JSON.stringify(LATEST)};
export const LATEST_TITLE = ${JSON.stringify(CHANGES[0].title)};
`;

if (process.argv.includes('--check')) {
	const have = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
	const haveTiny = fs.existsSync(TINY) ? fs.readFileSync(TINY, 'utf8') : '';
	if (have === text && haveTiny === tiny) {
		console.log('CHANGELOG.md and js/release.js are up to date');
		process.exit(0);
	}
	console.error(`${have === text ? 'js/release.js' : 'CHANGELOG.md'} is stale — run: node tools/build-changelog.mjs`);
	process.exit(1);
}

fs.writeFileSync(OUT, text);
fs.writeFileSync(TINY, tiny);
console.log(`wrote CHANGELOG.md — ${RELEASES.length} release(s), ${RELEASES[0].sections.length} sections`);
