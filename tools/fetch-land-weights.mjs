// Writes js/land_weights.js: what one of each land good weighs, in LT,
// read off its codex item page ("Weight: 0.10 LT"). The [Level N]
// goods weigh what GOODS in js/barter.js says; the land goods a chain
// starts from had no weight at all, so a hold loaded with Wool or
// Vinegar read as empty. Run after tools/build-land-goods.mjs when the
// list changes; goods with no codex id are reported and left out.

import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { landGoods } from '../js/land_goods.js';

const OUT = new URL('../js/land_weights.js', import.meta.url);
const UA = 'Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/128 Safari/537.36';

async function weightOf(id) {
	for (let tries = 0; tries < 3; tries++) {
		const res = await fetch(`https://bdocodex.com/us/item/${id}/`, { headers: { 'User-Agent': UA } }).catch(() => null);
		if (res && res.ok) {
			const m = /Weight:\s*([\d.]+)\s*LT/.exec(await res.text());
			if (m) return Number(m[1]);
		}
		await new Promise(r => setTimeout(r, 1500));
	}
	return null;
}

export async function fetchLandWeights() {
	const names = Object.keys(landGoods);
	const out = {}, missing = [];
	let next = 0;
	const worker = async () => {
		while (next < names.length) {
			const name = names[next++];
			const id = landGoods[name];
			const w = id ? await weightOf(id) : null;
			if (w == null) missing.push(name); else out[name] = w;
		}
	};
	await Promise.all([worker(), worker(), worker(), worker()]);
	const body = Object.keys(out).sort((a, b) => a.localeCompare(b)).map(n => `\t${JSON.stringify(n)}: ${out[n]}`).join(',\n');
	await writeFile(OUT, `// What one of each land good weighs, in LT, read off its codex item
// page. Generated by tools/fetch-land-weights.mjs -- do not edit by
// hand.
//
// ${Object.keys(out).length} goods${missing.length ? `; no weight found for ${missing.sort().join(', ')}` : ''}.

export const landWeights = {
${body}
};
`);
	return { found: Object.keys(out).length, missing };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
	const { found, missing } = await fetchLandWeights();
	console.log(`js/land_weights.js: ${found} weights${missing.length ? `, none for ${missing.join(', ')}` : ''}`);
}
