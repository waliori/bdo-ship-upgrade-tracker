// The icon BDOCodex draws beside each of our quests.
//
// A quest's icon is not derivable from its id: the codex names the file
// after the thing rather than the quest -- Ravinia's letters are all
// `rabinia.webp`, the Old Moon Guild's hunts share three, the swordfish
// weekly gets a fishing rod -- so the only way to it is the quest dump,
// whose icon column carries the path. There are far fewer files than
// quests, which is the point: the icon says what kind of errand this is
// at a glance, and a row of them reads as a set.
//
//   node tools/fetch-quest-icons.mjs [--dry-run]
//
// Downloads what is missing into icons/quest/ and rewrites
// js/quest_icons.js. The dump is 20 MB and is fetched once.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { quests } from '../js/quests.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DRY = process.argv.includes('--dry-run');
const BASE = 'https://bdocodex.com';
const HEADERS = {
	'User-Agent': 'Mozilla/5.0 (X11; Linux x86_64; rv:141.0) Gecko/20100101 Firefox/141.0',
	'Accept': 'text/html,application/xhtml+xml,application/xml;q=0.9,*/*;q=0.8',
	'Accept-Language': 'en-US,en;q=0.5',
	'Referer': `${BASE}/us/`,
	'Cookie': 'bddatabaselang=us'
};

const dir = path.join(ROOT, 'icons', 'quest');
fs.mkdirSync(dir, { recursive: true });

console.log('reading the quest dump…');
const res = await fetch(`${BASE}/query.php?a=quests&l=us`, { headers: HEADERS });
if (!res.ok) throw new Error(`quest dump: ${res.status}`);
// The dump is served with a BOM, which JSON.parse will not have.
const rows = JSON.parse((await res.text()).replace(/^﻿/, '')).aaData;
const byId = new Map(rows.map(r => [r[0].display, r]));
console.log(`  ${rows.length} quests`);

const icons = {};
const missing = [];
for (const q of quests) {
	if (!q.codex) continue;
	const row = byId.get(q.codex);
	const m = row && /src="\/items\/quest\/([^"]+)"/.exec(row[1]);
	if (!m) { missing.push(`${q.codex} ${q.name}`); continue; }
	icons[q.codex] = m[1];
}
console.log(`  ${Object.keys(icons).length} of ours have an icon, ${new Set(Object.values(icons)).size} files`);
for (const m of missing) console.log(`  no icon: ${m}`);

let got = 0;
for (const file of new Set(Object.values(icons))) {
	const to = path.join(dir, file);
	if (fs.existsSync(to)) continue;
	if (DRY) { console.log(`  would fetch ${file}`); continue; }
	const img = await fetch(`${BASE}/items/quest/${file}`, { headers: HEADERS });
	if (!img.ok) { console.log(`  ${file}: ${img.status}`); continue; }
	fs.writeFileSync(to, Buffer.from(await img.arrayBuffer()));
	got++;
}
console.log(`  ${got} downloaded`);

if (DRY) process.exit(0);
const body = Object.entries(icons).map(([id, file]) => `\t'${id}': '${file}'`).join(',\n');
fs.writeFileSync(path.join(ROOT, 'js', 'quest_icons.js'),
	`// The icon BDOCodex draws beside each quest, by its codex id.
//
// Generated by tools/fetch-quest-icons.mjs -- do not edit by hand.
// The files are under icons/quest/. Far fewer files than quests: the
// codex names them after the errand, so a row of quests reads as a set
// -- every Ravinia letter one picture, every Old Moon Guild hunt
// another. A quest with no entry here has none on the codex.
//
// Read ${new Date().toISOString().slice(0, 10)}.

export const QUEST_ICONS = {
${body}
};

/** The icon for a quest, as a path the page can use, or '' if it has none. */
export const questIcon = q => (q && QUEST_ICONS[q.codex] ? \`icons/quest/\${QUEST_ICONS[q.codex]}\` : '');
`);
console.log('js/quest_icons.js written');
